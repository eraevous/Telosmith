"""`aec agents`: render the shared governance part of AGENTS.md from `.aec/config.json` (DEC-256 item 4).

Seven repositories restated the same governance ideas in AGENTS.md, each in different words. This module renders
them once: the order to read things in, who holds which authority, the records and append-only ledgers, the hard
rules every Telosmith-based repository shares, run and drift, and a pointer to the glossary (DEC-255). Every
repository-specific value comes from the `agents.*` keys of the config (src/aec/config.py), so the text is the same
everywhere except where a repository says otherwise.

The block sits between two marker lines. `aec agents write` replaces only what lies between them, so a re-render
never touches the repository's own sections; a file without markers is refused unless `--append` is given, which
adds the block at the end. `aec agents check` exits 1 when the block is missing or differs from a fresh render (for
CI). Rendering is deterministic and reads nothing but the config. Standard library only.
"""
from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

from .config import Config, ConfigError, own

BEGIN = "<!-- telosmith:agents:begin (generated by `aec agents write` from .aec/config.json; edit that, not this block) -->"
END = "<!-- telosmith:agents:end -->"
BEGIN_PREFIX = "<!-- telosmith:agents:begin"
VOCABULARY = "https://github.com/eraevous/Telosmith/blob/main/docs/reasoning-vocabulary.md"


class AgentsError(ValueError):
    """AGENTS.md can't be read or written safely; the message names the file and the reason."""


def render(cfg: Config) -> str:
    """The shared block, markers included, ending in a newline. Deterministic for a given config."""
    owner = str(cfg.get("agents.owner"))
    records = str(cfg.get("records"))
    read_first = cfg.get("agents.read_first")
    ledgers = [records] + [p for p in cfg.get("agents.ledgers") if p != records]
    glossary = cfg.get("agents.glossary")
    rules = cfg.get("agents.hard_rules")

    out = [BEGIN, "", "## Shared governance (Telosmith)", "",
           "This section is the same in every Telosmith-based repository, apart from the values in "
           "`.aec/config.json`. The sections outside it are this repository's own; where they are more specific, "
           "they win for this repository.", "",
           "### Read first, in order of precedence", "",
           f"1. The purpose records in `{records}` (the latest version of each). If a change would break one, "
           "stop and raise it."]
    out += [f"{i}. `{p}`" for i, p in enumerate(read_first, start=2)]
    out += ["", "If a spec, plan or task conflicts with the purpose, the purpose wins until "
            f"{owner} decides otherwise. Don't resolve the conflict yourself: record it and say so.", "",
            "### Authority", "",
            "- **Domain truth** comes from the sources this repository names (specifications, data, rules). "
            "Agents cite them; they never decide them.",
            f"- **Design intent** belongs to {owner}. Agents may *propose* a decision (append it with status "
            f"`proposed`) and *challenge* one; only {owner} accepts. A typed `authorized_by` is a claim, not "
            "verified consent.",
            "- **Operational** rules (this file, CI, hooks) decide how work is done and checked. They never "
            "decide intent or domain truth.", "",
            "### Records and ledgers", "",
            "These files are append-only. Never rewrite or delete a line; append a new version instead.", ""]
    out += [f"- `{p}`" for p in ledgers]
    out += ["", f"Record terms are defined in the reasoning vocabulary: {VOCABULARY}", "",
            "### Hard rules", "",
            "- Never edit an existing record or ledger line.",
            "- Never accept a decision, or promote a claim to verified, on your own. A passing check is "
            "structural evidence, not owner approval.",
            "- Never hand-edit a generated file (`.aec/edges.jsonl`, a rendered block like this one); regenerate it.",
            "- Label every claim with its verification state; keep what a person said apart from what a model "
            "inferred."]
    out += [f"- {r}" for r in rules]
    out += ["", "### Run and drift", "",
            "- **Run:** implement authorized work, test it, keep moving. Note a non-obvious trade-off where this "
            "repository keeps intent notes.",
            "- **Drift:** stop and check the plan still serves the purpose when you are about to add a subsystem "
            "or change a module's responsibility, a spec or plan is revised, something downstream starts deriving "
            "what something upstream owns, most of the effort is going into machinery, or the work would cross a "
            "purpose record. Write a short dissent review: what it might violate, the evidence, the "
            "counter-evidence, what follows if the concern is right, and what to test or escalate.", "",
            "### Terms", ""]
    if glossary:
        out.append(f"Write records, pull requests and docs in the standard terms of the glossary: `{glossary}`.")
    else:
        out.append("No glossary is configured (`agents.glossary` in `.aec/config.json`); use the reasoning "
                   "vocabulary above for record terms.")
    out += ["", END]
    return "\n".join(out) + "\n"


def _split(text: str, path: Path) -> tuple[str, str, str] | None:
    """(before, block, after) when the file has exactly one well-formed marker pair, None when it has none."""
    lines = text.splitlines(keepends=True)
    begins = [i for i, ln in enumerate(lines) if ln.strip().startswith(BEGIN_PREFIX)]
    ends = [i for i, ln in enumerate(lines) if ln.strip() == END]
    if not begins and not ends:
        return None
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise AgentsError(f"{path}: expected one begin marker followed by one end marker, found "
                          f"{len(begins)} begin and {len(ends)} end; fix the markers by hand")
    b, e = begins[0], ends[0]
    return "".join(lines[:b]), "".join(lines[b:e + 1]), "".join(lines[e + 1:])


def _read(path: Path) -> str | None:
    if path.is_symlink():
        raise AgentsError(f"{path}: is a symlink; refused (the block is only written inside the repository)")
    if not path.exists():
        return None
    if not path.is_file():
        raise AgentsError(f"{path}: not a regular file")
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise AgentsError(f"{path}: can't read it ({error})") from None


def updated(text: str | None, block: str, path: Path, append: bool) -> str:
    """The new file text: the block swapped in between the markers, or appended when allowed."""
    if text is None:
        if not append:
            raise AgentsError(f"{path}: doesn't exist; use --append to create it with the shared block")
        return block
    parts = _split(text, path)
    if parts is None:
        if not append:
            raise AgentsError(f"{path}: has no telosmith:agents markers; add them where the block belongs, "
                              "or use --append to add the block at the end")
        return text.rstrip("\n") + "\n\n" + block if text.strip() else block
    before, _, after = parts
    return before + block + after


def _write(path: Path, text: str) -> None:
    """Replace PATH atomically: a temporary file in the same folder, renamed over it (never through a symlink)."""
    fd, tmp = tempfile.mkstemp(prefix=".agents-", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        if path.exists() and not path.is_symlink():
            os.chmod(tmp, path.stat().st_mode & 0o777)
        if path.is_symlink():
            raise AgentsError(f"{path}: became a symlink while writing; refused")
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def add_parser(sub) -> None:
    p = sub.add_parser("agents", help="render the shared governance block of AGENTS.md from .aec/config.json")
    a_sub = p.add_subparsers(dest="agents_cmd", required=True)
    for name, text in (("show", "print the block"),
                       ("write", "replace the block between the markers in AGENTS.md (nothing else changes)"),
                       ("check", "exit 0 only when AGENTS.md holds the block exactly as rendered")):
        c = a_sub.add_parser(name, help=text)
        c.add_argument("--repo", default=".", help="repository root; its own .aec/config.json is read (default: .)")
        if name != "show":
            c.add_argument("--file", default="AGENTS.md", help="relative to --repo (default: AGENTS.md)")
        if name == "write":
            c.add_argument("--append", action="store_true",
                           help="add the block at the end when the file has no markers (or create the file)")


def cli(a, ap) -> int:
    try:
        block = render(own(a.repo))
    except ConfigError as error:
        print(f"agents: config: {error}", file=sys.stderr)
        return 1
    if a.agents_cmd == "show":
        sys.stdout.write(block)
        return 0
    rel = Path(a.file)
    if rel.is_absolute() or ".." in rel.parts or a.file != a.file.strip():
        print(f"agents: --file must be a relative path inside the repository, got {a.file!r}", file=sys.stderr)
        return 1
    root = Path(a.repo)
    here = root
    for part in rel.parts[:-1]:
        here = here / part
        if here.is_symlink():
            print(f"agents: {here} is a symlink; refused", file=sys.stderr)
            return 1
    path = root / rel
    try:
        text = _read(path)
        if a.agents_cmd == "check":
            parts = _split(text, path) if text is not None else None
            if parts is None:
                print(f"agents: {path}: no shared block; run `aec agents write --repo {a.repo}`", file=sys.stderr)
                return 1
            if parts[1] != block:
                print(f"agents: {path}: the shared block differs from .aec/config.json; run "
                      f"`aec agents write --repo {a.repo}`", file=sys.stderr)
                return 1
            print(f"agents: ok ({path})")
            return 0
        new = updated(text, block, path, a.append)
        if new == text:
            print(f"agents: {path} already up to date")
            return 0
        _write(path, new)
    except AgentsError as error:
        print(f"agents: {error}", file=sys.stderr)
        return 1
    print(f"agents: wrote the shared block to {path}")
    return 0
